// Writes src/lib/mcp/registry.generated.ts: one import per src/lib/<module>/mcp.ts that exports `tools`. Runs in
// `npm run build`; run it yourself after adding a module's mcp.ts (`npx tsx scripts/gen-mcp-registry.ts`).
// --check: exit 1 if the file is out of date (used by the tests).
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const lib = join(__dirname, "..", "src", "lib");
const target = join(lib, "mcp", "registry.generated.ts");
const modules = readdirSync(lib, { withFileTypes: true })
  .filter((d) => d.isDirectory() && d.name !== "mcp" && existsSync(join(lib, d.name, "mcp.ts")))
  .map((d) => d.name)
  .sort();
const id = (m: string) => m.replace(/\W+/g, "_");
const out = [
  "// Generated by scripts/gen-mcp-registry.ts. Don't edit: add src/lib/<module>/mcp.ts exporting `tools` and rebuild.",
  'import type { AnyTool } from "./tool";',
  ...modules.map((m) => `import { tools as ${id(m)} } from "../${m}/mcp";`),
  "",
  `export const moduleTools: AnyTool[] = [${modules.map((m) => `...${id(m)}`).join(", ")}];`,
  "",
].join("\n");

const current = existsSync(target) ? readFileSync(target, "utf8") : "";
if (process.argv.includes("--check")) {
  if (current !== out) {
    console.error("✗ src/lib/mcp/registry.generated.ts is out of date. Run: npx tsx scripts/gen-mcp-registry.ts");
    process.exit(1);
  }
  console.log(`✓ MCP registry is current (${modules.join(", ")})`);
} else if (current !== out) {
  writeFileSync(target, out, "utf8");
  console.log(`MCP registry: ${modules.join(", ")}`);
}
